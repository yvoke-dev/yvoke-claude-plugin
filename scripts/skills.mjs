// The pure half of the skill stub generator (P1-04): turns the server's playbook catalogue, as the
// list_playbooks and list_areas tools return it, into one SKILL.md per playbook. No I/O here; the command
// line in generate-skills.mjs fetches the catalogue and writes the files. See docs/specs/skills.md.

// Every stub carries this line; the generator touches no SKILL.md, and removes no folder, without it.
export const GENERATED_MARKER = '<!-- Generated by scripts/generate-skills.mjs from the Yvoke server. Do not edit; rerun the script. -->'

// The Agent Skills limit on a skill's description.
export const DESCRIPTION_LIMIT = 1024

// Lowercase letters, digits and single hyphens, at most 64 characters: the Agent Skills name rule.
const SKILL_NAME = /^[a-z0-9]+(-[a-z0-9]+)*$/

const text = (value) => (typeof value === 'string' && value.trim() !== '' ? value.trim() : null)

// One list_playbooks entry. A field of the wrong type is dropped, not passed on: yvoke-desktop once read
// every playbook's metadata from the wrong place and nothing noticed (promptMapping.test.ts).
export function readPlaybook(raw) {
  const name = typeof raw?.name === 'string' ? raw.name : ''
  return {
    name,
    title: text(raw?.title) ?? name,
    description: typeof raw?.description === 'string' ? raw.description : '',
    targetAgent: text(raw?.targetAgent),
    prototype: raw?.prototype === true,
    area: text(raw?.area),
    systemPrompt: text(raw?.systemPrompt),
  }
}

// One list_areas entry, reduced to what choosing the base instructions needs.
export function readArea(raw) {
  return {
    name: text(raw?.name),
    defaultSystemPrompt: text(raw?.defaultSystemPrompt),
    systemPrompts: Array.isArray(raw?.systemPrompts) ? raw.systemPrompts.filter((p) => typeof p === 'string') : [],
  }
}

// The playbooks a user can pick: no orchestrator or reviewer, no prototype, every area. Sorted by name.
export function selectPlaybooks(playbooks) {
  return playbooks
    .filter((p) => !['orchestrator', 'reviewer'].includes(p.targetAgent?.toLowerCase()) && !p.prototype)
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
}

// The get_system_prompt arguments for a playbook, by P1-07's rule: its own system prompt when any area
// lists it as a chat prompt (yvoke-web's findChatPrompt looks a name up globally); else its area, when the
// area has a default; else none, which is the server's active default.
export function basePromptArgs(playbook, areas) {
  if (playbook.systemPrompt && areas.some((a) => a.systemPrompts.includes(playbook.systemPrompt))) {
    return { name: playbook.systemPrompt }
  }
  const area = areas.find((a) => a.name === playbook.area)
  if (area?.defaultSystemPrompt) return { area: area.name }
  return {}
}

// The frontmatter description: area prefix, one line, no angle brackets, cut on a word boundary.
export function stubDescription(playbook) {
  const prefix = playbook.area ? `Yvoke playbook (${playbook.area}): ` : 'Yvoke playbook: '
  const full = (prefix + (playbook.description.trim() || playbook.title)).replace(/\s+/g, ' ').trim().replace(/</g, '(').replace(/>/g, ')')
  if (full.length <= DESCRIPTION_LIMIT) return full
  const room = full.slice(0, DESCRIPTION_LIMIT) // one character spare for the ellipsis
  const cut = room.lastIndexOf(' ')
  // No word boundary after the prefix: cut the word itself rather than leave only the prefix.
  if (cut < prefix.length) return `${full.slice(0, DESCRIPTION_LIMIT - 1)}…`
  return `${room.slice(0, cut).replace(/[\s,;:—-]+$/, '')}…`
}

function systemPromptStep(args) {
  if (args.name) return `with \`name\` set to \`${args.name}\``
  if (args.area) return `with \`area\` set to \`${args.area}\``
  return 'with no arguments'
}

export function renderStub(playbook, areas) {
  const inArea = playbook.area ? ` in the area ${playbook.area}` : ''
  return [
    '---',
    `name: ${playbook.name}`,
    // JSON is a subset of YAML 1.2, so this reads back unchanged whatever the description holds.
    `description: ${JSON.stringify(stubDescription(playbook))}`,
    'disable-model-invocation: true',
    '---',
    '',
    GENERATED_MARKER,
    '',
    `# ${playbook.title}`,
    '',
    `This is the Yvoke playbook \`${playbook.name}\`${inArea}. Its instructions are kept on the Yvoke server, not in this file. Before you answer anything:`,
    '',
    `1. Call the Yvoke connector's \`get_system_prompt\` tool ${systemPromptStep(basePromptArgs(playbook, areas))}. Its text is your base instructions.`,
    `2. Call the Yvoke connector's \`get_playbook\` tool with \`name\` set to \`${playbook.name}\`, and follow the \`text\` it returns. Where the two disagree, the playbook wins.`,
    '3. If either call fails or returns a line starting with `ERROR:`, stop and show the user that error as it is. Do not answer from general knowledge.',
    '',
  ].join('\n')
}

// The whole set: a Map from skill folder name to SKILL.md text, in name order. Throws, and so writes
// nothing, on a bad name, a duplicate, or an empty result.
export function planSkills(catalogue) {
  if (!Array.isArray(catalogue?.playbooks)) throw new Error('the playbook catalogue is not a list')
  if (!Array.isArray(catalogue.areas)) throw new Error('the catalogue\'s areas is not a list')
  const areas = catalogue.areas.map(readArea)
  const playbooks = selectPlaybooks(catalogue.playbooks.map(readPlaybook))
  if (playbooks.length === 0) throw new Error('the server listed no playbooks to generate a skill for')

  const invalid = playbooks.filter((p) => !SKILL_NAME.test(p.name) || p.name.length > 64).map((p) => JSON.stringify(p.name))
  if (invalid.length) throw new Error(`not a valid skill name: ${invalid.join(', ')}`)
  const dup = playbooks.filter((p, i) => i > 0 && playbooks[i - 1].name === p.name).map((p) => JSON.stringify(p.name))
  if (dup.length) throw new Error(`more than one playbook is named ${[...new Set(dup)].join(', ')}`)

  return new Map(playbooks.map((p) => [p.name, renderStub(p, areas)]))
}
